import { readFile, writeFile } from 'node:fs/promises';

type QuestionLike = { topic: string };

const sourceUrl = new URL('../src/content/index.ts', import.meta.url);
const source = await readFile(sourceUrl, 'utf8');
const importsSection = source.slice(0, source.indexOf('export const allQuestions'));
const importPattern = /import\s*\{([^}]+)\}\s*from\s*['"]\.\/([^'"]+)['"];?/g;
const groups: Array<{ path: string; exports: string[]; topics: string[] }> = [];

for (const match of importsSection.matchAll(importPattern)) {
  const path = match[2];
  if (path === 'types') continue;

  const exports = match[1]
    .split(',')
    .map((name) => name.trim())
    .filter(Boolean);
  const module = await import(`../src/content/${path}/index.ts`) as Record<string, unknown>;
  const questions = exports.flatMap((name) => {
    const value = module[name];
    if (!Array.isArray(value)) throw new Error(`${path} does not export question array ${name}`);
    return value as QuestionLike[];
  });

  groups.push({
    path,
    exports,
    topics: [...new Set(questions.map(({ topic }) => topic))].sort(),
  });
}

const duplicateTopics = new Map<string, string[]>();
for (const group of groups) {
  for (const topic of group.topics) {
    duplicateTopics.set(topic, [...(duplicateTopics.get(topic) ?? []), group.path]);
  }
}
for (const [topic, paths] of duplicateTopics) {
  if (paths.length > 1) throw new Error(`Topic ${topic} appears in multiple groups: ${paths.join(', ')}`);
}

const loaderLines = groups.map(({ path, exports }) => {
  const expression = exports.length === 1
    ? `module.${exports[0]}`
    : `[${exports.map((name) => `...module.${name}`).join(', ')}]`;
  return `  ${JSON.stringify(path)}: () => import('./${path}').then((module) => ${expression}),`;
});

const topicMap = Object.fromEntries(
  groups.flatMap(({ path, topics }) => topics.map((topic) => [topic, path])),
);

const output = `// Generated by scripts/generate-question-loaders.ts. Do not edit by hand.\n` +
`import type { Question } from './types';\n\n` +
`const GROUP_LOADERS: Record<string, () => Promise<Question[]>> = {\n${loaderLines.join('\n')}\n};\n\n` +
`const TOPIC_TO_GROUP: Record<string, string> = ${JSON.stringify(topicMap, null, 2)};\n\n` +
`const groupCache = new Map<string, Promise<Question[]>>();\n\n` +
`function loadGroup(group: string): Promise<Question[]> {\n` +
`  const cached = groupCache.get(group);\n` +
`  if (cached) return cached;\n` +
`  const loader = GROUP_LOADERS[group];\n` +
`  if (!loader) return Promise.resolve([]);\n` +
`  const request = loader().catch((error) => {\n` +
`    groupCache.delete(group);\n` +
`    throw error;\n` +
`  });\n` +
`  groupCache.set(group, request);\n` +
`  return request;\n` +
`}\n\n` +
`export interface QuestionLoadProgress { loaded: number; total: number }\n\n` +
`export async function loadQuestionsForTopics(\n` +
`  topics: string[],\n` +
`  onProgress?: (progress: QuestionLoadProgress) => void,\n` +
`): Promise<Question[]> {\n` +
`  const groups = topics.length === 0\n` +
`    ? Object.keys(GROUP_LOADERS)\n` +
`    : [...new Set(topics.map((topic) => TOPIC_TO_GROUP[topic]).filter(Boolean))];\n` +
`  let loaded = 0;\n` +
`  onProgress?.({ loaded, total: groups.length });\n` +
`  const pools = await Promise.all(groups.map(async (group) => {\n` +
`    const questions = await loadGroup(group);\n` +
`    loaded += 1;\n` +
`    onProgress?.({ loaded, total: groups.length });\n` +
`    return questions;\n` +
`  }));\n` +
`  const pool = pools.flat();\n` +
`  return topics.length === 0 ? pool : pool.filter((question) => topics.includes(question.topic));\n` +
`}\n`;

await writeFile(new URL('../src/content/question-loaders.ts', import.meta.url), output);
console.log(`Generated ${groups.length} question groups covering ${duplicateTopics.size} topics.`);